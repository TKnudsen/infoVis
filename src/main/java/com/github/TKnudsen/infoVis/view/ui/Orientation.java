package com.github.TKnudsen.infoVis.view.ui;

/**
 * <p>
 * Horizontal or vertical orientation for graphical marks and channels.
 * </p>
 *
 * @version 1.0
 */
public enum Orientation {
	/**
	 * The horizontal orientation. Graphical marks and channels are aligned from
	 * left to right.
	 */
	HORIZONTAL,

	/**
	 * The vertical orientation. Graphical marks and channels are aligned top-down
	 * and vice versa.
	 */
	VERTICAL
}
